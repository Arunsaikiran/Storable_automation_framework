"""Builds the framework's YAML for one table pair: the reconciliation, the SQL and the files.

This file makes no database calls. The generator reads the columns and keys (db_rules.py), and this file:
  1. Normalises column names and reconciles the two sides by exact match (no fuzzy matching, no schema check). A column
     on one side only stays in the comparison, and the side that lacks it holds a token (MISSING_IN_SOURCE or _TARGET).
  2. Builds one normalised SELECT for the source and one for the Snowflake table. Each column becomes text
     in the same way on both sides, so the framework can compare them.
  3. Adds the optional row filters (the same condition on the count and on the data query).
  4. Writes the YAML files that the framework's main.py reads.

Why normalise: the two databases store the same value in different types. A boolean is true/false in
PostgreSQL and 1/0 in SQL Server, and a timestamp prints differently in each. The rules are in db_rules.py.

Known limits (see docs/YAML_GENERATION_GUIDE.md)
  - Only simple types have a format rule. Other types are cast to text as they are and listed in the header.
  - The framework runs str.format() on the target query. A curly brace in the SQL would crash it, so _checked() refuses
    every brace except {env} in a target query, which the framework fills in for the run's environment.
  - Filters are SQL text written by the user. They are checked for the forbidden characters only, not for meaning.

Self-check: python yaml_generation/yaml_builder.py
"""

import os
import re
import sys
import tempfile
from dataclasses import dataclass, field
from datetime import datetime
from pathlib import Path

import yaml

FRAMEWORK_ROOT = Path(__file__).resolve().parents[1]
if str(FRAMEWORK_ROOT) not in sys.path:  # lets the self-check run as a plain script
    sys.path.insert(0, str(FRAMEWORK_ROOT))

from yaml_generation.db_rules import RULES, kind_of, normalize_type, quote  # noqa: E402

# Every Snowflake Bronze query keeps only the latest active record (Fivetran rule, CLAUDE.md).
FIVETRAN_FILTER = "_FIVETRAN_ACTIVE = TRUE"

# Written in place of NULL, so a NULL on one side and a NULL on the other still compare equal.
NULL_TOKEN = "<<NULL>>"

# Written for a column that exists on one side only. The other side holds a different token, so every row of that column
# differs and the data validation reports it. Such a column is never dropped from the comparison.
MISSING_IN_SOURCE = "<<MISSING_IN_SOURCE>>"
MISSING_IN_TARGET = "<<MISSING_IN_TARGET>>"

# The environment in a Snowflake name, e.g. {env}_EDGE_BRONZE. The validators fill it in with DEV, STG, QAT or PRD (str.format).
ENV_PLACEHOLDER = "{env}"

# A normalised name that can be used as an alias without quoting.
PLAIN_NAME = re.compile(r"^[a-z_][a-z0-9_]*$")

# Every file this generator writes starts with this text. generated_tables() uses it to recognise the generator's own files.
GENERATED_MARK = "# Generated by yaml_generation/generate_yaml.py"

# Text that is never allowed inside a filter. Each one breaks the generated query, or hides the rest of it.
# A line break is refused too: the filter is written into the header and the SQL as one line.
FORBIDDEN_IN_FILTER = [";", "{", "}", "--", "/*", "*/", "\n", "\r"]

# TRUE and FALSE as words, and text that is quoted ('...') or bracketed ([...]), which is skipped when looking for them.
BARE_BOOLEAN = re.compile(r"\b(true|false)\b", re.IGNORECASE)
QUOTED = re.compile(r"'[^']*'|\[[^\]]*\]")


def normalize_name(name: str) -> str:
    """The form both sides are compared in: trimmed, lower case, spaces and hyphens become underscores.

    'Access Note' -> 'access_note', 'ACCESS-NOTE' -> 'access_note'. Exact match is then done on this form.
    """
    return re.sub(r"[\s\-]+", "_", name.strip()).lower()


def alias_for(normalized: str) -> str:
    """Name of the normalised column in both queries, e.g. 'id' -> 'id_normalized'."""
    return f"{normalized}_normalized"


def check_filter(text, label: str, source_type=None, placeholders=False):
    """Return the filter text, or None when it is empty. Refuses text that would break the generated SQL.

    Pass source_type for a SOURCE filter only: SQL Server has no TRUE or FALSE, so a bit column is written as 1 or 0.
    Pass placeholders=True for a TARGET filter: {env} is allowed there, as in the Snowflake database name.
    Text inside quotes or brackets is not checked for those words.
    """
    if text is None or not str(text).strip():
        return None
    text = str(text).strip()
    probe = text.replace(ENV_PLACEHOLDER, "") if placeholders else text
    for bad in FORBIDDEN_IN_FILTER:
        if bad in probe:
            raise ValueError(f"{label}: the filter may not contain {bad!r}: {text}")
    if source_type == "mssql" and BARE_BOOLEAN.search(QUOTED.sub("", text)):
        raise ValueError(f"{label}: SQL Server has no TRUE or FALSE. Write 1 or 0 for a bit column: {text}")
    return text


@dataclass
class TableSpec:
    """One table pair. table is the source name; it is also the YAML key and the file name."""

    source_type: str      # postgres | mssql | athena | redshift
    source_schema: str    # e.g. edge, dbo, or the Glue database for Athena
    table: str            # source table name
    target_database: str  # Snowflake database name as written in the YAML, e.g. {env}_EDGE_BRONZE
    target_schema: str    # e.g. EDGE, SITELINK

    @property
    def target_table(self) -> str:
        """Snowflake table name: upper case, as the existing framework files show it (gate_access_event -> GATE_ACCESS_EVENT)."""
        return self.table.upper()


@dataclass
class Filters:
    """Optional row filters, one per side. Each is a SQL condition without the word WHERE, or None.

    source_window and target_window are the incremental window of an incremental run (window_condition). They are
    added after the filters, on the same side.
    """

    source_where: str = None
    target_where: str = None
    source_window: str = None
    target_window: str = None

    def source_parts(self) -> list:
        return [f"({part})" for part in (self.source_where, self.source_window) if part]

    def target_parts(self) -> list:
        return [FIVETRAN_FILTER] + [f"({part})" for part in (self.target_where, self.target_window) if part]


def window_condition(column_sql: str) -> str:
    """The incremental window: the rows changed after the last run, up to the Fivetran sync.

    The validators replace :start_time (the last run, or the Fivetran minimum) and :end_time (the sync, or the Fivetran
    maximum) with the values they work out at run time. The YAML holds only the placeholders, never a date.
    """
    return f"{column_sql} > :start_time AND {column_sql} <= :end_time"


def incremental_window(pairs, column: str, source_rules: dict):
    """(source_window, target_window) on the incremental column, or None when it is not compared on both sides."""
    norm = normalize_name(column)
    for source, _, target, _, name in pairs:
        if name == norm and source and target:
            return window_condition(quote(source, source_rules)), window_condition(quote(target, RULES["snowflake"]))
    return None


@dataclass
class Reconciliation:
    """Outcome of matching the two column lists.

    pairs    = [(source_name, source_type, target_name, target_type, normalised_name), ...] to be compared.
               A side is None when the column is not on that side; its token is written in the SQL instead.
    rows     = [(source_name, target_name, status, note), ...] one per column, for the reconciliation report
    problems = reasons the data file cannot be built from these columns (text)
    """

    pairs: list = field(default_factory=list)
    rows: list = field(default_factory=list)
    problems: list = field(default_factory=list)


def reconcile(source_columns, target_columns, global_excluded, table_excluded, source_rules) -> Reconciliation:
    """Match source and target columns by normalised name, after applying the exclusions. Exact match only.

    A column on one side only is kept in pairs (MISSING_IN_TARGET, EXTRA_IN_TARGET), so it is compared and shows up as
    a difference. Only the exclusions remove a column.

    Statuses: MATCHED, MISSING_IN_TARGET (source only), EXTRA_IN_TARGET (target only),
              EXCLUDED_GLOBAL and EXCLUDED_TABLE (excluded by the global or the table list).
    """
    result = Reconciliation()
    target_by_norm = {}
    for name, dtype in target_columns:
        target_by_norm.setdefault(normalize_name(name), (name, dtype))
    matched = set()

    for name, dtype in source_columns:
        norm = normalize_name(name)
        target = target_by_norm.get(norm)
        excluded = "EXCLUDED_GLOBAL" if norm in global_excluded else "EXCLUDED_TABLE" if norm in table_excluded else None
        if target:
            matched.add(norm)
        if excluded:
            result.rows.append((name, target[0] if target else "", excluded, ""))
        elif target is None:
            result.rows.append((name, "", "MISSING_IN_TARGET", ""))
            result.pairs.append((name, dtype, None, None, norm))
        else:
            result.pairs.append((name, dtype, target[0], target[1], norm))
            result.rows.append((name, target[0], "MATCHED", ""))

    for name, dtype in target_columns:
        norm = normalize_name(name)
        if norm in matched:
            continue
        if norm in global_excluded:
            status = "EXCLUDED_GLOBAL"
        elif norm in table_excluded:
            status = "EXCLUDED_TABLE"
        else:
            status = "EXTRA_IN_TARGET"
            result.pairs.append((None, None, name, dtype, norm))
        result.rows.append(("", name, status, ""))

    result.problems = comparability_problems(result.pairs, source_rules)
    return result


def comparability_problems(pairs, source_rules) -> list:
    """Reasons the compared columns cannot be used. An empty list means they can.

    Refused: two names that normalise to the same form, a normalised name that cannot be an alias,
    and a type that cannot be compared as text on this source (for example SQL Server geography).
    A column on one side only is not read as a value, so its type does not matter.
    """
    problems = []
    seen = {}
    for source, source_type, target, _, norm in pairs:
        name = source or target
        if norm in seen:
            problems.append(f"'{seen[norm]}' and '{name}' both become '{norm}'")
        seen.setdefault(norm, name)
        if not PLAIN_NAME.match(norm):
            problems.append(f"'{name}' cannot become a name without special characters")
        if source and target and normalize_type(source_type) in source_rules["refused_types"]:
            problems.append(f"'{source}' is type {source_type}, which cannot be compared as text on {source_rules['label']}")
    return problems


def missing_key_columns(key_columns, pairs) -> list:
    """Key columns that are not in both databases: missing on one side, excluded, or not found."""
    both = {p[4] for p in pairs if p[0] and p[2]}
    return [k for k in key_columns if normalize_name(k) not in both]


def key_expression(key_columns) -> str:
    """The key as the framework reads it: one alias, or several joined with commas (ADR 0072 A3).

    ['id'] -> 'id_normalized'; ['company_id', 'site_id'] -> 'company_id_normalized,site_id_normalized'.
    """
    return ",".join(alias_for(normalize_name(column)) for column in key_columns)


def value_expression(column_sql: str, data_type: str, rules: dict) -> str:
    """The SQL expression for one value, before the cast to text. column_sql is already quoted.

    Columns without a rule are returned as they are, and the header lists them.
    """
    kind = kind_of(data_type, rules)
    if kind == "boolean":
        return (f"CASE WHEN {column_sql} = {rules['true']} THEN 'TRUE' "
                f"WHEN {column_sql} = {rules['false']} THEN 'FALSE' ELSE NULL END")
    if kind == "timestamp":
        return rules["timestamp"].format(c=column_sql)
    if kind == "date":
        return rules["date"].format(c=column_sql)
    if kind == "text":
        return rules["trim"].format(c=column_sql)
    if kind == "large_text":
        # A large-text column cannot go into TRIM() directly on SQL Server. Trim the cast value instead,
        # so the value is trimmed the same way as a normal text column on the other side.
        return rules["trim"].format(c=f"CAST({column_sql} AS {rules['text_type']})")
    return column_sql


def normalized_item(column: str, alias: str, data_type: str, rules: dict) -> str:
    """One SELECT item: COALESCE(CAST(<value> AS <text type>), '<<NULL>>') AS <alias>. The column name is quoted."""
    expr = value_expression(quote(column, rules), data_type, rules)
    return f"COALESCE(CAST({expr} AS {rules['text_type']}), '{NULL_TOKEN}') AS {alias}"


def _checked(sql: str, placeholders=False) -> str:
    """Refuse SQL with a curly brace. The framework calls str.format() on target queries, which would crash.

    Pass placeholders=True for a target query: {env} is then allowed, because the framework fills it in.
    """
    probe = sql.replace(ENV_PLACEHOLDER, "") if placeholders else sql
    if "{" in probe or "}" in probe:
        raise ValueError(f"Generated SQL contains a curly brace, which the framework cannot run: {sql[:120]}")
    return sql


def _select(items, from_clause: str, where_parts=(), placeholders=False) -> str:
    """One statement: one column per line, the WHERE conditions joined with AND, and a final semicolon."""
    lines = ["SELECT", "  " + ",\n  ".join(items), f"FROM {from_clause}"]
    if where_parts:
        lines.append("WHERE " + "\n  AND ".join(where_parts))
    return _checked("\n".join(lines) + ";", placeholders)


def source_ref(spec: TableSpec, rules: dict) -> str:
    """The source table as written in FROM, e.g. "public"."units". The connection picks the database."""
    return f"{quote(spec.source_schema, rules)}.{quote(spec.table, rules)}"


def target_ref(spec: TableSpec) -> str:
    """The Snowflake table as written in FROM. The database name is unquoted, so Snowflake matches it in any case."""
    snow = RULES["snowflake"]
    return f"{spec.target_database}.{quote(spec.target_schema, snow)}.{quote(spec.target_table, snow)}"


def side_item(column, alias: str, data_type, rules: dict, missing_token: str) -> str:
    """One SELECT item for one side. A column this side does not have gets the token, so its rows differ from the other side."""
    if column is None:
        return f"CAST('{missing_token}' AS {rules['text_type']}) AS {alias}"
    return normalized_item(column, alias, data_type, rules)


def flattened_columns(pairs, source_rules: dict) -> dict:
    """alias -> source type, for the columns compared as flattened JSON (jsonb, json, hstore), on both sides.

    The validator flattens them with utils/json_normalize.py, so keys and spacing do not decide the comparison.
    """
    return {alias_for(n): s_type for s, s_type, t, _, n in pairs if s and t and kind_of(s_type, source_rules) == "json"}


def build_data_entry(spec: TableSpec, pairs, key_columns, filters: Filters) -> dict:
    """The data_validation block: both normalised SELECTs, the key, and the names the framework reads."""
    source_rules = RULES[spec.source_type]
    snow = RULES["snowflake"]
    key = key_expression(key_columns)
    source_items = [side_item(s, alias_for(n), s_type, source_rules, MISSING_IN_SOURCE) for s, s_type, _, _, n in pairs]
    target_items = [side_item(t, alias_for(n), t_type, snow, MISSING_IN_TARGET) for _, _, t, t_type, n in pairs]
    entry = {
        "source_table_name": spec.table,
        "source": spec.source_type,
        "source_schema": spec.source_schema,
        "sourcecolumn": key,
        "sourcequery": _select(source_items, source_ref(spec, source_rules), filters.source_parts()),
        "target_table_name": spec.target_table,
        "target": "snowflake",
        "target_database": spec.target_database,
        "target_schema": spec.target_schema,
        "targetcolumn": key,
        "targetquery": _select(target_items, target_ref(spec), filters.target_parts(), placeholders=True),
    }
    flattened = flattened_columns(pairs, source_rules)
    if flattened:
        entry["json_columns"] = flattened
    return entry


def build_count_entry(spec: TableSpec, filters: Filters) -> dict:
    """The count_validation block. Each query returns one row with one number, under the same filters as the data."""
    source_rules = RULES[spec.source_type]
    source_where = " AND ".join(filters.source_parts())
    target_where = " AND ".join(filters.target_parts())
    source_sql = f"SELECT COUNT(*) AS source_row_count FROM {source_ref(spec, source_rules)}"
    target_sql = f"SELECT COUNT(*) AS target_row_count FROM {target_ref(spec)}"
    return {
        "source_table_name": spec.table,
        "source": spec.source_type,
        "source_schema": spec.source_schema,
        "sourcequery": _checked(source_sql + (f" WHERE {source_where}" if source_where else "") + ";"),
        "target_table_name": spec.target_table,
        "target": "snowflake",
        "target_database": spec.target_database,
        "target_schema": spec.target_schema,
        "targetquery": _checked(target_sql + f" WHERE {target_where};", placeholders=True),
    }


def plain_text_columns(pairs, source_rules) -> list:
    """Columns with no format rule. They are compared as plain text, and may FAIL on formatting alone."""
    return [f"{source} ({source_type})" for source, source_type, target, _, _ in pairs
            if source and target and kind_of(source_type, source_rules) == "other"]


def data_header(spec: TableSpec, key: str, rec: Reconciliation, filters: Filters, stamp: str) -> list:
    """Comment lines at the top of a data file: where the data comes from, the key, filters, and what was left out."""
    source_rules = RULES[spec.source_type]
    lines = [
        f"{GENERATED_MARK} on {stamp}. Do not hand-edit; main.py --yaml_generation yes rewrites it when the structure changes.",
        f"# Source: {source_rules['label']} {spec.source_schema}.{spec.table}",
        f"# Target: {spec.target_database}.{spec.target_schema}.{spec.target_table} (Snowflake, _FIVETRAN_ACTIVE = TRUE)",
        f"# Key: {key}   Columns compared: {len(rec.pairs)}",
    ]
    if filters.source_where:
        lines.append(f"# Source filter: {filters.source_where}")
    if filters.target_where:
        lines.append(f"# Target filter: {filters.target_where}")
    if filters.source_window:
        lines.append(f"# Incremental window (source): {filters.source_window}   (validators bind :start_time, :end_time)")
    if filters.target_window:
        lines.append(f"# Incremental window (target): {filters.target_window}")
    for status, label in [("EXCLUDED_GLOBAL", "Excluded (global list)"), ("EXCLUDED_TABLE", "Excluded (table rule)"),
                          ("MISSING_IN_TARGET", f"Source columns not in Snowflake (compared as {MISSING_IN_TARGET}, "
                                                "so every row differs)"),
                          ("EXTRA_IN_TARGET", f"Snowflake columns not in source (compared as {MISSING_IN_SOURCE}, "
                                              "so every row differs)")]:
        names = [src or tgt for src, tgt, s, _ in rec.rows if s == status]
        if names:
            lines.append(f"# {label}: " + ", ".join(names))
    plain = plain_text_columns(rec.pairs, source_rules)
    if plain:
        lines.append("# Compared as plain text, no format rule (may FAIL on formatting alone): " + ", ".join(plain))
    flattened = flattened_columns(rec.pairs, source_rules)
    if flattened:
        lines.append("# Compared as flattened JSON text (json_columns, both sides): " + ", ".join(sorted(flattened)))
    return lines


COUNT_HEADER = [
    "# Row-count checks for every table in this layer, written by yaml_generation/generate_yaml.py.",
    "# Do not hand-edit. A table that is generated again is replaced in place; other tables are kept.",
    "# No timestamp is written here on purpose: this file is shared, so a timestamp would change on every run.",
]


class _Dumper(yaml.SafeDumper):
    """Writes multi-line SQL as YAML block text (|), so the files read like the existing framework files."""


def _str_as_block(dumper, text):
    style = "|" if "\n" in text else None
    return dumper.represent_scalar("tag:yaml.org,2002:str", text, style=style)


_Dumper.add_representer(str, _str_as_block)


def _dump(doc) -> str:
    # width=inf stops PyYAML from folding long single-line values. sort_keys=False keeps the field order.
    return yaml.dump(doc, Dumper=_Dumper, sort_keys=False, allow_unicode=True, width=float("inf"))


def _write_text(path: Path, text: str) -> None:
    """Write through a temporary file with a unique name, then rename it into place."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.NamedTemporaryFile("w", encoding="utf-8", newline="\n", dir=path.parent,
                                     prefix=path.name + ".", suffix=".tmp", delete=False) as f:
        f.write(text)
        tmp = f.name
    os.replace(tmp, path)


def _without_stamp(text: str) -> str:
    """The file text without its first line. That line holds the run time, which is not a change in the content."""
    return text.split("\n", 1)[1] if text.startswith(GENERATED_MARK) else text


def write_data_file(config_dir, spec: TableSpec, entry: dict, header: list):
    """Write <config_dir>/data_validation/<table>.yaml. One table per file.

    Returns (path, status). status is NEW (no file before), UPDATED (the content changed) or UNCHANGED.
    An UNCHANGED file is not touched, so its stamp shows when its content last changed.
    """
    path = Path(config_dir) / "data_validation" / f"{spec.table}.yaml"
    doc = {"tables": {spec.table: {"validations": {"data_validation": entry}}}}
    text = "\n".join(header) + "\n\n" + _dump(doc)
    if not path.exists():
        _write_text(path, text)
        return path, "NEW"
    if _without_stamp(path.read_text(encoding="utf-8")) == _without_stamp(text):
        return path, "UNCHANGED"
    _write_text(path, text)
    return path, "UPDATED"


def data_file_path(config_dir, table: str) -> Path:
    """Where the data YAML for a table is written. One file per table, the same for every environment."""
    return Path(config_dir) / "data_validation" / f"{table}.yaml"


def _count_tables(config_dir, layer: str) -> dict:
    """The {table: block} map in the count file, or {} when there is no file."""
    path = Path(config_dir) / "count_validation" / f"{layer}.yaml"
    if not path.exists():
        return {}
    return (yaml.safe_load(path.read_text(encoding="utf-8")) or {}).get("tables") or {}


def count_table_names(config_dir, layer: str) -> set:
    """Names of the tables in the layer's count file. Empty when there is no file."""
    return set(_count_tables(config_dir, layer))


def generated_tables(config_dir, layer: str, target_database: str, source_schema: str) -> set:
    """Tables this generator wrote from source_schema: a data file with GENERATED_MARK, or a count entry for target_database.

    Only tables from source_schema are listed. A run for one schema must not remove the generated tables of another,
    so a file or entry that does not name this schema (or that has no schema) is left alone.
    """
    names = set()
    data_dir = Path(config_dir) / "data_validation"
    if data_dir.exists():
        for path in data_dir.glob("*.yaml"):
            with open(path, encoding="utf-8") as f:
                if not f.readline().startswith(GENERATED_MARK):
                    continue
            doc = yaml.safe_load(path.read_text(encoding="utf-8")) or {}
            entry = (((doc.get("tables") or {}).get(path.stem) or {}).get("validations") or {}).get("data_validation") or {}
            if entry.get("source_schema") == source_schema:
                names.add(path.stem)
    for table, block in _count_tables(config_dir, layer).items():
        entry = ((block or {}).get("validations") or {}).get("count_validation") or {}
        if entry.get("target_database") == target_database and entry.get("source_schema") == source_schema:
            names.add(table)
    return names


def upsert_count_file(config_dir, layer: str, entries: dict):
    """Add or replace tables in <config_dir>/count_validation/<layer>.yaml, keeping every other table.

    entries = {table_name: count_entry}. A table already in the file keeps its position.
    Returns (path, statuses), where statuses = {table: NEW | UPDATED | UNCHANGED} for each entry, or None when
    there was nothing to write. The file is written only when a table changes or a table is removed.
    """
    path = Path(config_dir) / "count_validation" / f"{layer}.yaml"
    if not entries and not path.exists():
        return None
    before = _count_tables(config_dir, layer)
    tables = dict(before)
    statuses = {}
    for table, entry in entries.items():
        block = {"validations": {"count_validation": entry}}
        statuses[table] = "NEW" if table not in before else "UNCHANGED" if before[table] == block else "UPDATED"
        tables[table] = block
    if path.exists() and tables == before:
        return path, statuses
    _write_text(path, "\n".join(COUNT_HEADER) + "\n\n" + _dump({"tables": tables}))
    return path, statuses


def other_environment_tables(config_dir, layer: str, target_database: str) -> list:
    """Tables in the shared count file that point at a different Snowflake database (for example DEV while this run is PRD).

    The framework reads one file per layer, with no environment in its path (ADR 0072 A1).
    """
    path = Path(config_dir) / "count_validation" / f"{layer}.yaml"
    if not path.exists():
        return []
    tables = (yaml.safe_load(path.read_text(encoding="utf-8")) or {}).get("tables") or {}
    found = []
    for table, block in tables.items():
        entry = ((block or {}).get("validations") or {}).get("count_validation") or {}
        if entry.get("target_database") not in (None, target_database):
            found.append(table)
    return sorted(found)


